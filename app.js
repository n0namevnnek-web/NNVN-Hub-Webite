function formatSize(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

function formatRelativeTime(dateValue) {
  const diffMs = Date.now() - new Date(dateValue).getTime();
  const diffHours = Math.max(1, Math.floor(diffMs / 3600000));
  if (diffHours < 24) {
    return state.lang === "vi" ? `${diffHours} giờ trước` : `${diffHours} hours ago`;
  }
  const diffDays = Math.floor(diffHours / 24);
  return state.lang === "vi" ? `${diffDays} ngày trước` : `${diffDays} days ago`;
}

function createPreview(label, index) {
  const palettes = [
    ["#15203a", "#ffe3af", "#cc8cb0"],
    ["#141f37", "#f4faff", "#77b5eb"],
    ["#261848", "#ffe2a8", "#9577d6"],
    ["#15203a", "#f8fbff", "#6cb7df"]
  ];
  const [bg, fg, glow] = palettes[index % palettes.length];
  const svg = `
    <svg xmlns="http://www.w3.org/2000/svg" width="800" height="500" viewBox="0 0 800 500">
      <rect width="800" height="500" rx="40" fill="${bg}" />
      <circle cx="170" cy="100" r="82" fill="rgba(255,255,255,0.08)" />
      <circle cx="660" cy="120" r="116" fill="${glow}" fill-opacity="0.46" />
      <path d="M-60 340 C 180 270, 320 420, 860 180" stroke="rgba(255,255,255,0.28)" stroke-width="48" fill="none" stroke-linecap="round" />
      <text x="58" y="360" fill="${fg}" font-family="Outfit, Arial" font-size="56" font-weight="700">${escapeXml(shorten(label, 18))}</text>
    </svg>
  `;
  return `data:image/svg+xml;charset=UTF-8,${encodeURIComponent(svg)}`;
}

function createViewStore() {
  const config = window.NNVN_BACKEND || {};
  const enabled = Boolean(config.supabaseUrl && config.supabaseAnonKey);

  return {
    enabled,
    async fetchCounts(ids) {
      if (!enabled) {
        const fallback = {};
        ids.forEach((id) => {
          fallback[id] = Number(localStorage.getItem(`nnvn-demo-view:${id}`) || 0);
        });
        return fallback;
      }

      try {
        const url = new URL(`${config.supabaseUrl}/rest/v1/script_metrics`);
        url.searchParams.set("select", "script_id,views");
        url.searchParams.set("script_id", `in.(${ids.join(",")})`);
        const response = await fetch(url, {
          headers: {
            apikey: config.supabaseAnonKey,
            Authorization: `Bearer ${config.supabaseAnonKey}`
          }
        });
        const rows = await response.json();
        return Object.fromEntries(rows.map((row) => [row.script_id, row.views]));
      } catch {
        return {};
      }
    },
    async bump(id) {
      if (!enabled) {
        const next = Number(localStorage.getItem(`nnvn-demo-view:${id}`) || 0) + 1;
        localStorage.setItem(`nnvn-demo-view:${id}`, String(next));
        return next;
      }

      const dedupeKey = `nnvn-live-view:${id}:${new Date().toISOString().slice(0, 10)}`;
      if (localStorage.getItem(dedupeKey)) {
        const counts = await this.fetchCounts([id]);
        return counts[id] ?? 0;
      }

      try {
        const response = await fetch(`${config.supabaseUrl}/rest/v1/rpc/increment_script_view`, {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            apikey: config.supabaseAnonKey,
            Authorization: `Bearer ${config.supabaseAnonKey}`
          },
          body: JSON.stringify({ input_script_id: id })
        });
        const value = await response.json();
        localStorage.setItem(dedupeKey, "1");
        return Number(value) || 0;
      } catch {
        return 0;
      }
    }
  };
}

function shorten(value, maxLength) {
  return value.length > maxLength ? `${value.slice(0, maxLength - 1)}…` : value;
}

function escapeXml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}
