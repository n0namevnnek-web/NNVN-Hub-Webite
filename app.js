function validateLuau(source) {
  if (!source.trim()) {
    return { ok: false, reason: "validationEmpty" };
  }

  const stack = [];
  const pairs = { "(": ")", "{": "}", "[": "]" };
  let quote = null;
  let escape = false;

  for (const char of source) {
    if (quote) {
      if (escape) {
        escape = false;
        continue;
      }
      if (char === "\\") {
        escape = true;
        continue;
      }
      if (char === quote) {
        quote = null;
      }
      continue;
    }

    if (char === '"' || char === "'") {
      quote = char;
      continue;
    }

    if (pairs[char]) {
      stack.push(pairs[char]);
      continue;
    }

    if (Object.values(pairs).includes(char)) {
      if (stack.pop() !== char) {
        return { ok: false, reason: "validationInvalid" };
      }
    }
  }

  if (quote || stack.length) {
    return { ok: false, reason: "validationInvalid" };
  }

  return { ok: true, reason: "validationOk" };
}

function normalizeLuauText(text) {
  return text
    .replaceAll("“", '"')
    .replaceAll("”", '"')
    .replaceAll("‘", "'")
    .replaceAll("’", "'");
}

