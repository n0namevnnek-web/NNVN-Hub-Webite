function formatDate(dateValue) {
  const formatter = new Intl.DateTimeFormat(state.lang === "vi" ? "vi-VN" : "en-US", {
    day: "2-digit",
    month: "short",
    year: "numeric"
  });
  return formatter.format(new Date(dateValue));
}

