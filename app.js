function createViewStore() {
  const config = window.NNVN_BACKEND || {};
  const enabled = Boolean(config.supabaseUrl && config.supabaseAnonKey);

  return {
    enabled,
    async fetchCounts(ids) {
      if (!enabled) {
        const fallback = {};
        ids.forEach((id) => {
          fallback[id] = Number(localStorage.getItem(`nnvn-demo-view:${id}`) || 0);
        });
        return fallback;
      }

      try {
        const url = new URL(`${config.supabaseUrl}/rest/v1/script_metrics`);
        url.searchParams.set("select", "script_id,views");
        url.searchParams.set("script_id", `in.(${ids.join(",")})`);
        const response = await fetch(url, {
          headers: {
            apikey: config.supabaseAnonKey,
            Authorization: `Bearer ${config.supabaseAnonKey}`
          }
        });
        const rows = await response.json();
        return Object.fromEntries(rows.map((row) => [row.script_id, row.views]));
      } catch {
        return {};
      }
    },
    async bump(id) {
      if (!enabled) {
        const next = Number(localStorage.getItem(`nnvn-demo-view:${id}`) || 0) + 1;
        localStorage.setItem(`nnvn-demo-view:${id}`, String(next));
        return next;
      }

      const dedupeKey = `nnvn-live-view:${id}:${new Date().toISOString().slice(0, 10)}`;
      if (localStorage.getItem(dedupeKey)) {
        const counts = await this.fetchCounts([id]);
        return counts[id] ?? 0;
      }

      try {
        const response = await fetch(`${config.supabaseUrl}/rest/v1/rpc/increment_script_view`, {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            apikey: config.supabaseAnonKey,
            Authorization: `Bearer ${config.supabaseAnonKey}`
          },
          body: JSON.stringify({ input_script_id: id })
        });
        const value = await response.json();
        localStorage.setItem(dedupeKey, "1");
        return Number(value) || 0;
      } catch {
        return 0;
      }
    }
  };
}

function shorten(value, maxLength) {
  return value.length > maxLength ? `${value.slice(0, maxLength - 1)}…` : value;
}

function escapeXml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}
